const ELEMENT_SUB_COLORS: Record<Element, string> = {
  blaze: '#d06830',
  frost: '#50a0c0',
  volt: '#c0a040',
  venom: '#9060b0',
  alloy: '#8098a0',
  mirage: '#c060d0',
};

interface MonsterSpriteProps {
  monsterId: string;
  element: Element;
  size?: number;
  animate?: boolean;
  hurt?: boolean;
}

export function MonsterSprite({ monsterId, element, size = 32, animate, hurt }: MonsterSpriteProps) {
  const sprite = SPRITES[monsterId] || DEFAULT_SPRITE;
  const pixelSize = size / 8;
  const mainColor = ELEMENT_COLORS[element];
  const subColor = ELEMENT_SUB_COLORS[element];
  const accentColor = '#3a2a1a';

  const colorMap: Record<number, string> = {
    1: mainColor,
    2: subColor,
    3: accentColor,
  };

  return (
    <div style={{
      width: size, height: size,
      display: 'grid',
      gridTemplateColumns: `repeat(8, ${pixelSize}px)`,
      gridTemplateRows: `repeat(8, ${pixelSize}px)`,
      imageRendering: 'pixelated',
      animation: animate ? 'spriteIdle 1.2s ease-in-out infinite' : hurt ? 'spriteHurt 0.3s ease' : undefined,
      filter: hurt ? 'brightness(2)' : undefined,
    }}>
      {sprite.flat().map((pixel, i) => (
        <div key={i} style={{
          background: pixel === 0 ? 'transparent' : colorMap[pixel] || mainColor,
          width: pixelSize,
          height: pixelSize,
        }} />
      ))}
    </div>
  );
}
