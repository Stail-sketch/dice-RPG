function renderSpriteToDataURL(spriteDef: SpriteDef): string {
  const canvas = document.createElement('canvas');
  canvas.width = 32;
  canvas.height = 32;
  const ctx = canvas.getContext('2d')!;
  ctx.clearRect(0, 0, 32, 32);

  const { palette, data } = spriteDef;
  for (let y = 0; y < 32; y++) {
    for (let x = 0; x < 32; x++) {
      const ch = data[y * 32 + x];
      if (ch === '0') continue;
      const color = palette[ch];
      if (!color) continue;
      ctx.fillStyle = color;
      ctx.fillRect(x, y, 1, 1);
    }
  }
  return canvas.toDataURL();
}

function resolveBaseId(monsterId: string): string {
  // SPRITESに直接あればそのまま
  if (SPRITES[monsterId]) return monsterId;
  // インスタンスID（例: pyrachnid_001_1234）→ baseId部分を抽出
  // パターン: baseId_NNN_NNNN or baseId_NNN
  const match = monsterId.match(/^(.+?)_\d{3}/);
  if (match && SPRITES[match[1]]) return match[1];
  return monsterId;
}

function getSpriteDataURL(monsterId: string): string {
  const baseId = resolveBaseId(monsterId);
  if (spriteCache.has(baseId)) return spriteCache.get(baseId)!;
  const def = SPRITES[baseId] || DEFAULT_SPRITE;
  const url = renderSpriteToDataURL(def);
  spriteCache.set(baseId, url);
  return url;
}

// ---------------------------------------------------------------------------
// Component
// ---------------------------------------------------------------------------

interface MonsterSpriteProps {
  monsterId: string;
  element: Element;
  size?: number;
  animate?: boolean;
  hurt?: boolean;
}

export function MonsterSprite({ monsterId, element: _element, size = 64, animate, hurt }: MonsterSpriteProps) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const dataURLRef = useRef<string>('');

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    // Get or build cached data URL
    const url = getSpriteDataURL(monsterId);
    dataURLRef.current = url;

    const img = new Image();
    img.onload = () => {
      ctx.imageSmoothingEnabled = false;
      ctx.clearRect(0, 0, size, size);
      ctx.drawImage(img, 0, 0, size, size);
    };
    img.src = url;
  }, [monsterId, size]);

  const animationName = hurt ? 'spriteHurt' : animate ? 'spriteIdle' : undefined;
  const animationDuration = hurt ? '0.3s' : '1.2s';
  const animationTimingFunction = hurt ? 'ease' : 'ease-in-out';
  const animationIterationCount = hurt ? '1' : 'infinite';

  return (
    <canvas
      ref={canvasRef}
      width={size}
      height={size}
      style={{
        width: size,
        height: size,
        imageRendering: 'pixelated',
        animation: animationName
          ? `${animationName} ${animationDuration} ${animationTimingFunction} ${animationIterationCount}`
          : undefined,
        filter: hurt ? 'brightness(2)' : undefined,
      }}
    />
  );
}
